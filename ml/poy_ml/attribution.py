"""Generate ATTRIBUTION.md (repo) and attributions.json (About page) from the manifest's kept images.

Usage: python -m poy_ml.attribution
"""

from __future__ import annotations

import json

from poy_ml import config, manifest
from poy_ml.data_sources import ImageRecord

LICENSE_NAMES = {"cc0": "CC0", "pdm": "Public Domain", "by": "CC BY"}


def _md(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ").strip() or "unknown"


def render_markdown(records: list[ImageRecord]) -> str:
    kept = [r for r in records if r.status == "kept"]
    needs = sum(r.license == "by" for r in kept)
    lines = [
        "# Attribution",
        "",
        "Generated by `python -m poy_ml.attribution` from `ml/data/manifest.csv`. Do not edit by hand.",
        "",
        f"The base model was trained on hand landmarks from {len(kept)} images.",
        f"{needs} of them are CC BY and require the attribution below; the rest are CC0 or public "
        "domain and are credited as a courtesy. Images are not redistributed in this repository.",
        "",
        "The hand landmark model `hand_landmarker.task` is by Google (MediaPipe), Apache License 2.0.",
        "",
        "| Label | Title | Author | License | Source |",
        "|---|---|---|---|---|",
    ]
    for r in kept:
        lic = f"[{LICENSE_NAMES.get(r.license, r.license)}]({r.license_url})" if r.license_url else r.license
        lines.append(
            f"| {r.label} | [{_md(r.title)}]({r.page_url}) | {_md(r.author)} | {lic} | {r.source_api} |"
        )
    return "\n".join(lines) + "\n"


def render_json(records: list[ImageRecord]) -> list[dict[str, str]]:
    return [
        {
            "title": r.title,
            "author": r.author,
            "license": LICENSE_NAMES.get(r.license, r.license),
            "license_url": r.license_url,
            "page_url": r.page_url,
        }
        for r in records
        if r.status == "kept"
    ]


def main() -> None:
    records = manifest.read(config.MANIFEST_PATH)
    config.ATTRIBUTION_MD.write_text(render_markdown(records), encoding="utf-8")
    config.ATTRIBUTION_JSON.write_text(json.dumps(render_json(records), indent=1), encoding="utf-8")
    print(f"wrote {config.ATTRIBUTION_MD} and {config.ATTRIBUTION_JSON}")


if __name__ == "__main__":
    main()
